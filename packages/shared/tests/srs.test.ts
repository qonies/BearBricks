// TC-ENG-001/002：SRS 踢墙表逐值断言 + 功能性验证（标准 JLSTZ 表与 I 块专用表）

import { describe, expect, it } from 'vitest';
import { KICKS_I, KICKS_JLSTZ, PIECE_CELLS, pieceCells, kicksFor } from '../src/engine/srs';

describe('SRS 踢墙表（标准值）', () => {
  it('JLSTZ 0->R 标准五级偏移', () => {
    expect(KICKS_JLSTZ['01']).toEqual([[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]]);
  });

  it('JLSTZ 0->L 标准五级偏移', () => {
    expect(KICKS_JLSTZ['03']).toEqual([[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]]);
  });

  it('JLSTZ R->0 为 0->R 的逆', () => {
    expect(KICKS_JLSTZ['10']).toEqual([[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]]);
  });

  it('JLSTZ 2->L / L->2 对称', () => {
    expect(KICKS_JLSTZ['23']).toEqual([[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]]);
    expect(KICKS_JLSTZ['32']).toEqual([[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]]);
  });

  it('I 块专用表 0->R / 3->0', () => {
    expect(KICKS_I['01']).toEqual([[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]]);
    expect(KICKS_I['30']).toEqual([[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]]);
  });

  it('JLSTZ 全表 8 条逐值断言（TC-ENG-001）', () => {
    expect(KICKS_JLSTZ).toEqual({
      '01': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
      '10': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
      '12': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
      '21': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
      '23': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
      '32': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
      '30': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
      '03': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
    });
  });

  it('I 块全表 8 条逐值断言（TC-ENG-002）', () => {
    expect(KICKS_I).toEqual({
      '01': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
      '10': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
      '12': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
      '21': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
      '23': [[0, 0], [2, 0], [-1, 0], [2, 1], [-1, -2]],
      '32': [[0, 0], [-2, 0], [1, 0], [-2, -1], [1, 2]],
      '30': [[0, 0], [1, 0], [-2, 0], [1, -2], [-2, 1]],
      '03': [[0, 0], [-1, 0], [2, 0], [-1, 2], [2, -1]],
    });
  });

  it('O 块无踢墙偏移', () => {
    expect(kicksFor('O', 0, 1)).toEqual([[0, 0]]);
  });

  it('四个旋转形态的格子数均为 4 且 spawn 形态符合标准', () => {
    for (const t of ['I', 'O', 'T', 'S', 'Z', 'J', 'L'] as const) {
      expect(PIECE_CELLS[t]).toHaveLength(4);
      for (const rot of PIECE_CELLS[t]) expect(rot).toHaveLength(4);
    }
    expect(pieceCells('T', 0)).toEqual([[1, 0], [0, 1], [1, 1], [2, 1]]);
    expect(pieceCells('I', 0)).toEqual([[0, 1], [1, 1], [2, 1], [3, 1]]);
  });
});
