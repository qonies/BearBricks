export function kicksFor(type: PieceType, from: Rotation, to: Rotation): readonly (readonly [number, number])[] {
  if (type === 'O') return [[0, 0]] as const;
  const table = type === 'I' ? KICKS_I : KICKS_JLSTZ;
  return table[`${from}${to}`] ?? ([[0, 0]] as const);
}

export function pieceCells(type: PieceType, rot: Rotation): Cells {
  return PIECE_CELLS[type][rot];
}
